import assert from 'node:assert/strict'
import { loadAccountProfiles, importAccountProfile, currentAccountProfile, selectAccountProfile, updateAccountProfile, removeAccountProfile, PROFILES_KEY } from './account-profiles.js'
import { saveImportedAccount } from './user-data.js'
import { parseAccountProfilesFile } from './account.js'
const map = new Map(), store = { getItem: k => map.get(k) || null, setItem: (k,v) => map.set(k,v), removeItem: k => map.delete(k) }
const a = (region,id) => ({ ok: true, region, servants: [{ id, bondLv: 5 }], ces: [] })
saveImportedAccount(a('CN',1),100,store); saveImportedAccount(a('JP',2),101,store)
assert.equal(loadAccountProfiles(store).profiles.length,2)
const first = currentAccountProfile('CN',store)
const second = importAccountProfile(a('CN',3),{store,name:'备用号'})
assert.equal(loadAccountProfiles(store).profiles.length,3)
assert.equal(currentAccountProfile('CN',store).id,second.id)
updateAccountProfile(first.id,{planner:{lockIds:[1],costLimit:'55'}},store)
selectAccountProfile(first.id,store)
assert.deepEqual(currentAccountProfile('CN',store).planner.lockIds,[1])
importAccountProfile(a('CN',4),{id:first.id,store})
assert.equal(currentAccountProfile('CN',store).account.servants[0].id,4)
assert.deepEqual(currentAccountProfile('CN',store).planner.lockIds,[1])
assert.equal(loadAccountProfiles(store).profiles.find(p=>p.id===second.id).account.servants[0].id,3)
assert.throws(()=>importAccountProfile(a('JP',9),{id:first.id,store}),/区服/)
removeAccountProfile(first.id,store)
assert.equal(currentAccountProfile('CN',store).id,second.id)
assert.equal(currentAccountProfile('JP',store).account.servants[0].id,2)
removeAccountProfile(second.id,store)
assert.equal(currentAccountProfile('CN',store),null)
assert.equal(loadAccountProfiles(store).profiles.length,1)
map.set(PROFILES_KEY,'broken')
assert.match(loadAccountProfiles(store).error,/原数据已保留/)
assert.throws(()=>importAccountProfile(a('CN',8),{store}),/无法读取/)
assert.equal(map.get(PROFILES_KEY),'broken')
const imported=await parseAccountProfilesFile({users:[{region:'cn',svtStatus:{100100:{svtId:100100,bondLv:5}}},{region:'jp',svtStatus:{200100:{svtId:200100,bondLv:6}}}]})
assert.equal(imported.ok,true)
assert.equal(imported.accounts.length,2)
assert.deepEqual(imported.accounts.map(a=>a.servants.map(s=>s.id)),[[100100],[200100]])
assert.deepEqual(imported.accounts.map(a=>a.region),['CN','JP'])
console.log('Account profiles: legacy migration, isolated inventories/preferences, explicit refresh, region-safe deletion and multi-user separation passed')
